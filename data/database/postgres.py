"""PostgreSQL adapter for the SQLite-style queries used in Naija Bites.

Enabled only when DATABASE_URL is configured. This is intentionally limited
to our own schema and queries, not a general SQLite compatibility library.
"""
import re
import time
import os
from core.observability.metrics import record_db_query

import psycopg
from psycopg.rows import dict_row


class CompatRow(dict):
    def __getitem__(self, key):
        return list(self.values())[key] if isinstance(key, int) else super().__getitem__(key)


class CompatCursor:
    def __init__(self, cursor, lastrowid=None):
        self._cursor = cursor
        self.lastrowid = lastrowid

    @property
    def rowcount(self):
        return self._cursor.rowcount

    def fetchone(self):
        row = self._cursor.fetchone()
        return CompatRow(row) if row is not None else None

    def fetchall(self):
        return [CompatRow(row) for row in self._cursor.fetchall()]

    def __iter__(self):
        for row in self._cursor:
            yield CompatRow(row)


_ID_TABLES = frozenset(("products", "customers", "orders", "order_items"))


def translate_sql(sql):
    statement = sql.strip()
    statement = re.sub(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
                       "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                       statement, flags=re.I)
    statement = re.sub(r"\bTEXT(\s+(?:NOT\s+NULL\s+)?UNIQUE)\s+COLLATE\s+NOCASE\b",
                       r"CITEXT\1", statement, flags=re.I)
    statement = re.sub(r"\bDEFAULT\s+CURRENT_TIMESTAMP\b",
                       "DEFAULT (CURRENT_TIMESTAMP::text)", statement, flags=re.I)
    if re.match(r"INSERT\s+OR\s+IGNORE\s+INTO\b", statement, re.I):
        statement = re.sub(r"^INSERT\s+OR\s+IGNORE\s+INTO\b",
                           "INSERT INTO", statement, flags=re.I)
        statement = statement.rstrip(";") + " ON CONFLICT DO NOTHING"
    return statement.replace("?", "%s")


class PostgresConnection:
    """Supports with/commit/rollback, SQLite-style rows, and lastrowid."""

    def __init__(self, url):
        self._experimental_pooled = False
        if (os.getenv("NAIJA_BITES_POOL_EXPERIMENT") == "1"
                and os.getenv("NAIJA_BITES_EXPERIMENT_POOL_ENABLED") == "1"):
            from data.database import pool_experiment
            pool_experiment.guard()
            self._conn = pool_experiment.borrow()
            self._experimental_pooled = True
        else:
            self._conn = psycopg.connect(url, autocommit=True, row_factory=dict_row)
        self._transaction_open = False
        self._closed = False

    def __enter__(self):
        self._begin()
        return self

    def __exit__(self, exc_type, exc, tb):
        try:
            if exc_type is not None:
                self.rollback()
            else:
                self.commit()
        finally:
            self.close()
        return False

    def _begin(self):
        if not self._transaction_open:
            self._conn.execute("BEGIN")
            self._transaction_open = True

    def execute(self, sql, params=None):
        started = time.perf_counter()
        try:
            result = self._execute_untimed(sql, params)
        except Exception:
            record_db_query("postgres", (time.perf_counter() - started) * 1000, False)
            raise
        record_db_query("postgres", (time.perf_counter() - started) * 1000, True)
        return result

    def _execute_untimed(self, sql, params=None):
        statement = sql.strip()
        if re.fullmatch(r"BEGIN(?:\s+IMMEDIATE)?\s*;?", statement, re.I):
            self._begin()
            return CompatCursor(self._conn.execute("SELECT 1"))
        converted = translate_sql(sql)
        match = re.match(r"INSERT\s+INTO\s+(\w+)\b", converted, re.I)
        generated_id = bool(match and match.group(1).lower() in _ID_TABLES
                            and not re.search(r"\bRETURNING\b|\bON\s+CONFLICT\b", converted, re.I))
        if generated_id:
            converted = converted.rstrip(";") + " RETURNING id"
        cursor = self._conn.execute(converted, params)
        if generated_id:
            inserted = cursor.fetchone()
            return CompatCursor(cursor, inserted["id"] if inserted else None)
        return CompatCursor(cursor)

    def commit(self):
        if self._transaction_open:
            self._conn.execute("COMMIT")
            self._transaction_open = False

    def rollback(self):
        if self._transaction_open:
            self._conn.execute("ROLLBACK")
            self._transaction_open = False

    def close(self):
        if self._closed:
            return
        self._closed = True
        try:
            # A dead connection cannot roll back; return it to the pool, which
            # discards it rather than lending it to a different customer.
            if not self._conn.closed:
                try:
                    if self._transaction_open:
                        self.rollback()
                    elif self._experimental_pooled:
                        # Defensive cleanup before psycopg_pool's session reset.
                        self._conn.rollback()
                except psycopg.OperationalError:
                    # Failure during network loss may close the connection.
                    # Do not mask an earlier user operation with cleanup noise.
                    if not self._conn.closed:
                        raise
        finally:
            if self._experimental_pooled:
                from data.database import pool_experiment
                pool_experiment.release(self._conn)
            else:
                self._conn.close()
