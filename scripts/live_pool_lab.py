def reset(conn):
    if conn.info.transaction_status.name != "IDLE":
        conn.rollback()
    conn.execute("DISCARD ALL")

@contextmanager
def db(mode="fresh"):
    if mode == "pool":
        with _pool.connection() as conn:
            yield conn
    else:
        with psycopg.connect(DATABASE_URL, autocommit=True, row_factory=dict_row,
                             prepare_threshold=None, connect_timeout=8) as conn:
            yield conn

def record(mode, action, started, ok=True):
    with _metric_lock:
        _metrics[(mode, action)].append((round((time.perf_counter()-started)*1000, 2),ok))

def summary():
    with _metric_lock:
        items = list(_metrics.items())
    result = {}
    for (mode, action), vals in items:
        samples = [v for v, _ in vals]
        result[f"{mode}:{action}"] = {
            "count":len(vals),"errors":sum(not ok for _,ok in vals),
            "p50_ms":round(statistics.median(samples),2),
            "p95_ms":round(sorted(samples)[min(len(samples)-1,int(len(samples)*.95))],2)}
    return result

@asynccontextmanager
async def lifespan(app):
    global _pool
    with db() as conn:
        assert conn.execute("SHOW server_version_num").fetchone()["server_version_num"].startswith("18")
        for statement in SCHEMA.split(";"):
            if statement.strip():
                conn.execute(statement)
        for name, price in MENU:
            conn.execute("""INSERT INTO lab_products(name,price,stock) VALUES(%s,%s,200)
                ON CONFLICT(name) DO NOTHING""",(name,price))
    _pool = ConnectionPool(conninfo=DATABASE_URL, min_size=2,max_size=5,
        timeout=2.0, open=False,
        kwargs={"autocommit":True,"row_factory":dict_row,"prepare_threshold":None},
        reset=reset)
    _pool.open()
    _pool.wait(timeout=15)
    try:
        yield
    finally:
        _pool.close()

app = FastAPI(lifespan=lifespan,docs_url=None,redoc_url=None,openapi_url=None)

@app.middleware("http")
async def protect(request:Request,call_next):
    if request.url.path == "/" or request.url.path == "/healthz":
        return await call_next(request)
    key = request.headers.get("x-lab-key","")
    if not secrets.compare_digest(key, ACCESS_CODE):
        return JSONResponse({"detail":"Invalid lab access code"},status_code=401)
    if request.method != "GET" and request.headers.get("origin") != PUBLIC_ORIGIN:
        return JSONResponse({"detail":"Invalid test origin"},status_code=403)
    return await call_next(request)

def session(request:Request):
    sid = request.cookies.get("naija_lab_session","")
    if not re.fullmatch(r"[a-f0-9]{32}",sid):
        sid=secrets.token_hex(16)
    with db() as conn:
        conn.execute("INSERT INTO lab_sessions(id) VALUES(%s) ON CONFLICT DO NOTHING",(sid,))
        row=conn.execute("SELECT mode FROM lab_sessions WHERE id=%s",(sid,)).fetchone()
    return sid,row["mode"]

def respond(payload,sid):
    response=JSONResponse(payload)
    response.set_cookie("naija_lab_session",sid,secure=True,httponly=True,samesite="lax",max_age=86400)
    response.headers["Cache-Control"]="no-store"
    return response

def run(mode,action,fn):
    start=time.perf_counter()
    try:
        with db(mode) as conn:
            result=fn(conn)
        record(mode,action,start)
        return result
    except Exception:
        record(mode,action,start,False)
        raise

