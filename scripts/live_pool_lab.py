@app.post("/api/mode")
def change_mode(payload:Mode,request:Request):
    sid,_=session(request)
    if payload.mode not in ("fresh","pool"):
        raise HTTPException(400,"Choose fresh or pool")
    with db() as conn:
        conn.execute("UPDATE lab_sessions SET mode=%s WHERE id=%s",(payload.mode,sid))
    return respond({"mode":payload.mode},sid)

class Add(BaseModel):
    product_id:int
    quantity:int=Field(default=1,ge=1,le=5)
@app.post("/api/cart/add")
def add(payload:Add,request:Request):
    sid,mode=session(request)
    def write(conn):
        with conn.transaction():
            product=conn.execute("SELECT id,stock FROM lab_products WHERE id=%s",(payload.product_id,)).fetchone()
            if not product:
                raise HTTPException(404,"Meal not found")
            current=conn.execute("SELECT qty FROM lab_cart WHERE session_id=%s AND product_id=%s",
                (sid,payload.product_id)).fetchone()
            qty=(current["qty"] if current else 0)+payload.quantity
            if qty>5 or qty>product["stock"]:
                raise HTTPException(409,"Quantity exceeds available test stock or cart limit")
            conn.execute("""INSERT INTO lab_cart(session_id,product_id,qty) VALUES(%s,%s,%s)
                ON CONFLICT(session_id,product_id) DO UPDATE SET qty=EXCLUDED.qty""",
                (sid,payload.product_id,qty))
        return {"message":"Meal added to your test cart"}
    return respond(run(mode,"cart_add",write),sid)

@app.post("/api/cart/clear")
def clear(request:Request):
    sid,mode=session(request)
    run(mode,"cart_clear",lambda c:c.execute("DELETE FROM lab_cart WHERE session_id=%s",(sid,)))
    return respond({"message":"Cart cleared"},sid)

@app.post("/api/checkout")
def checkout(request:Request):
    sid,mode=session(request)
    def write(conn):
        with conn.transaction():
            conn.execute("SELECT id FROM lab_sessions WHERE id=%s FOR UPDATE",(sid,))
            count=conn.execute("SELECT count(*) AS n FROM lab_orders WHERE session_id=%s",(sid,)).fetchone()["n"]
            if count>=8:
                raise HTTPException(409,"Test order limit reached. Start a fresh private browser session.")
            rows=conn.execute("""SELECT c.product_id,c.qty,p.price,p.stock FROM lab_cart c
                JOIN lab_products p ON p.id=c.product_id
                WHERE c.session_id=%s ORDER BY c.product_id FOR UPDATE OF p""",(sid,)).fetchall()
            if not rows:
                raise HTTPException(409,"Add food to the cart first")
            for r in rows:
                if r["stock"]<r["qty"]:
                    raise HTTPException(409,"Test stock unavailable")
            total=sum(r["qty"]*r["price"] for r in rows)
            oid=conn.execute("INSERT INTO lab_orders(session_id,total) VALUES(%s,%s) RETURNING id",
                (sid,total)).fetchone()["id"]
            for r in rows:
                conn.execute("UPDATE lab_products SET stock=stock-%s WHERE id=%s",(r["qty"],r["product_id"]))
                conn.execute("""INSERT INTO lab_order_items(order_id,product_id,qty,unit_price)
                    VALUES(%s,%s,%s,%s)""",(oid,r["product_id"],r["qty"],r["price"]))
            conn.execute("DELETE FROM lab_cart WHERE session_id=%s",(sid,))
        return {"order_id":oid,"total":total,"status":"pending",
                "message":"Test order created. No real order or delivery."}
    return respond(run(mode,"checkout",write),sid)

class Payment(BaseModel):
    order_id:int
@app.post("/api/payment")
def payment(payload:Payment,request:Request):
    sid,mode=session(request)
    def write(conn):
        with conn.transaction():
            order=conn.execute("""SELECT id,status FROM lab_orders WHERE id=%s
                AND session_id=%s FOR UPDATE""",(payload.order_id,sid)).fetchone()
            if not order:
                raise HTTPException(404,"Test order not found")
            conn.execute("UPDATE lab_orders SET status='paid_simulated' WHERE id=%s",(payload.order_id,))
        return {"message":"Simulated payment confirmed. No money was charged."}
    return respond(run(mode,"mock_payment",write),sid)

class Chat(BaseModel):
    message:str=Field(min_length=1,max_length=250)
@app.post("/api/chat")
def chat(payload:Chat,request:Request):
    sid,mode=session(request)
    message=payload.message.strip().lower()
    def read(conn):
        return conn.execute("SELECT id,name,price,stock FROM lab_products ORDER BY id").fetchall()
    products=run(mode,"chat_menu_read",read)
    matched=next((p for p in products if p["name"].lower() in message),None)
    if not matched:
        matched=next((p for p in products if any(w in message for w in p["name"].lower().split()
                   if len(w)>4)),None)
    if any(w in message for w in ("add ","order ","buy ")) and matched:
        add(Add(product_id=matched["id"]),request)
        answer=f"Added {matched['name']} to your test cart! You can review and checkout below."
    elif any(w in message for w in ("menu","food","available","recommend","eat","hungry","price")):
        answer="Here is our fictional menu: "+", ".join(
            f"{p['name']} (₦{p['price']:,})" for p in products)+". Say 'add jollof' to try ordering."
    elif "cart" in message:
        answer="Your cart is shown below. Add a meal, then click Checkout to create a simulated order."
    elif "pay" in message:
        answer="After checkout, click Simulate payment. No Paystack call or real charge happens."
    elif "checkout" in message:
        answer="Click Checkout below to place a fictional order. We won't request your address or payment details."
    else:
        answer="I'm the simulated Naija Bites assistant, not a real AI model. Ask for the menu, say 'add jollof', or use the food buttons below."
    return respond({"reply":answer,"simulated":True,"mode":mode},sid)

