"""Isolated PostgreSQL migration and owner access integration tests.

Only runs against the disposable PostgreSQL instance provided by CI.
"""
import os
import unittest

from data.database import models
from core.services import auth_service, owner_dashboard_service
from core.services.owner_access_service import promote_registered_customer

EMAIL = "postgres-owner@example.test"


class OwnerPostgresTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        if os.getenv("NAIJA_BITES_POSTGRES_CI") != "1":
            raise unittest.SkipTest("Requires the isolated CI PostgreSQL service.")
        if not os.getenv("DATABASE_URL", "").startswith("postgresql://postgres:postgres@127.0.0.1:5432/"):
            raise RuntimeError("Refusing to run outside the isolated CI database.")
        # Model an old installation without the role column.
        with models.get_connection() as conn:
            conn.execute("CREATE EXTENSION IF NOT EXISTS citext")
            conn.execute("""CREATE TABLE customers (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT, email CITEXT UNIQUE, password_hash TEXT,
                phone TEXT UNIQUE, created_at TEXT DEFAULT CURRENT_TIMESTAMP::text
            )""")
        models.create_tables()
        models.create_tables()  # Re-running must be harmless.

    def test_roles_and_promotion(self):
        customer = auth_service.register_customer("PG Owner", EMAIL, "Fictional-PG-Password-12345")
        self.assertEqual(customer["role"], "customer")
        result = auth_service.login_customer(EMAIL, "Fictional-PG-Password-12345")
        token = result["session_token"]
        self.assertEqual(auth_service.authenticate_token(token)["role"], "customer")
        promoted = promote_registered_customer(EMAIL)
        self.assertEqual(promoted["role"], "owner")
        self.assertIsNone(auth_service.authenticate_token(token))
        logged_in = auth_service.login_customer(EMAIL, "Fictional-PG-Password-12345")
        self.assertEqual(logged_in["customer"]["role"], "owner")
        with models.get_connection() as conn:
            row = conn.execute("SELECT role FROM customers WHERE email=?", (EMAIL,)).fetchone()
            self.assertEqual(row["role"], "owner")
            audit = conn.execute("SELECT action FROM owner_audit_log").fetchall()
            self.assertEqual(audit[0]["action"], "promote_to_owner")

    def test_dashboard_queries(self):
        overview = owner_dashboard_service.overview()
        self.assertEqual(overview["paid_revenue"], 0)
        self.assertEqual(overview["order_count"], 0)
        self.assertEqual(owner_dashboard_service.list_orders(), [])
        self.assertEqual(owner_dashboard_service.list_menu(), [])
        self.assertEqual(owner_dashboard_service.list_customers(), [])


if __name__ == "__main__":
    unittest.main()
