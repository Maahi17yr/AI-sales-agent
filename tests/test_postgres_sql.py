"""SQL translation checks without needing a hosted database."""
import unittest

try:
    from database.postgres import translate_sql
except ImportError:
    translate_sql = None


@unittest.skipIf(translate_sql is None, "psycopg not installed")
class PostgresTranslationTests(unittest.TestCase):
    def test_identity(self):
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY",
                      translate_sql("id INTEGER PRIMARY KEY AUTOINCREMENT,"))

    def test_citext(self):
        self.assertEqual(translate_sql("email TEXT UNIQUE COLLATE NOCASE"),
                         "email CITEXT UNIQUE")

    def test_insert_ignore(self):
        self.assertEqual(
            translate_sql("INSERT OR IGNORE INTO inventory (product_id) VALUES (?)"),
            "INSERT INTO inventory (product_id) VALUES (%s) ON CONFLICT DO NOTHING")

    def test_upsert(self):
        self.assertIn("ON CONFLICT(session_id) DO UPDATE", translate_sql(
            "INSERT INTO conversation_sessions (session_id) VALUES (?) "
            "ON CONFLICT(session_id) DO UPDATE SET updated_at=CURRENT_TIMESTAMP"))


if __name__ == "__main__":
    unittest.main()
